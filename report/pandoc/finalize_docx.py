"""Apply report styles and resolve clickable contents page ranges.

Uses Microsoft Word on Windows and LibreOffice on Linux/macOS for pagination.
The body, figures and tables are generated by Pandoc from report.md.
"""
from pathlib import Path
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from docx import Document
from docx.enum.style import WD_STYLE_TYPE
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor


def styles(doc):
    for name in ['TOC 1', 'TOC 2', 'TOC Heading']:
        if name not in doc.styles:
            doc.styles.add_style(name, WD_STYLE_TYPE.PARAGRAPH)
    for style in doc.styles:
        if style.type in [WD_STYLE_TYPE.PARAGRAPH, WD_STYLE_TYPE.CHARACTER]:
            style.font.name = 'Times New Roman'
            style.font.color.rgb = RGBColor(0, 0, 0)
            for fonts in style.element.xpath('./w:rPr/w:rFonts'):
                for key in list(fonts.attrib):
                    if 'theme' in key.lower():
                        del fonts.attrib[key]
                for key in ['ascii', 'hAnsi', 'eastAsia', 'cs']:
                    fonts.set(qn('w:' + key), 'Times New Roman')
    for name in ['Normal', 'Body Text', 'First Paragraph']:
        if name in doc.styles:
            style = doc.styles[name]
            style.font.size = Pt(12)
            fmt = style.paragraph_format
            fmt.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            fmt.line_spacing = 1.15
            fmt.space_after = Pt(6)
            fmt.first_line_indent = Cm(0)
            fmt.widow_control = True
    for name, size in [('Title', 22), ('Subtitle', 16), ('Heading 1', 16), ('Heading 2', 13), ('TOC Heading', 18)]:
        style = doc.styles[name]
        style.font.size = Pt(size)
        style.font.bold = name != 'Subtitle'
        style.paragraph_format.keep_with_next = True
        style.paragraph_format.space_before = Pt(14 if name.startswith('Heading') else 0)
        style.paragraph_format.space_after = Pt(8)
        for node in list(style.element.xpath('./w:pPr/w:pBdr')):
            node.getparent().remove(node)
    for name in ['Source Code', 'Verbatim Char']:
        if name in doc.styles:
            doc.styles[name].font.name = 'Consolas'
            doc.styles[name].font.size = Pt(9)
            if name == 'Source Code':
                doc.styles[name].paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    for name in ['Caption', 'Image Caption', 'Table Caption']:
        if name in doc.styles:
            doc.styles[name].font.size = Pt(10)
            doc.styles[name].font.italic = False
            fmt = doc.styles[name].paragraph_format
            fmt.alignment = WD_ALIGN_PARAGRAPH.LEFT if name == 'Table Caption' else WD_ALIGN_PARAGRAPH.CENTER
            fmt.line_spacing = 1.05
            fmt.space_before = Pt(4)
            fmt.space_after = Pt(8)
    for name in ['TOC 1', 'TOC 2']:
        style = doc.styles[name]
        style.font.size = Pt(11)
        style.font.bold = name == 'TOC 1'
        fmt = style.paragraph_format
        fmt.line_spacing = 1.05
        fmt.space_after = Pt(4)
        fmt.space_before = Pt(0)
        fmt.left_indent = Cm(.6 if name == 'TOC 2' else 0)
    for section in doc.sections:
        section.page_width, section.page_height = Cm(21), Cm(29.7)
        section.left_margin, section.right_margin = Cm(2.5), Cm(2)
        section.top_margin, section.bottom_margin = Cm(2), Cm(2)
        section.header_distance, section.footer_distance = Cm(.8), Cm(.8)
        section.different_first_page_header_footer = True
        footer = section.footer.paragraphs[0]
        footer.clear()
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        field = OxmlElement('w:fldSimple')
        field.set(qn('w:instr'), 'PAGE')
        run = OxmlElement('w:r')
        text = OxmlElement('w:t')
        text.text = '1'
        run.append(text)
        field.append(run)
        footer._p.append(field)
    for table in doc.tables:
        table.autofit = False
        count = len(table.columns)
        if count == 3:
            widths = [2.3, 3.2, 10.9]
        elif table.cell(0, 0).text.startswith('Время'):
            widths = [2.9, 2.4, 5.6, 5.5]
        else:
            widths = [2.1, 4.6, 5.0, 4.7]
        for row_index, row in enumerate(table.rows):
            trpr = row._tr.get_or_add_trPr()
            if row_index == 0:
                trpr.append(OxmlElement('w:tblHeader'))
            trpr.append(OxmlElement('w:cantSplit'))
            for index, cell in enumerate(row.cells):
                cell.width = Cm(widths[index])
                tcpr = cell._tc.get_or_add_tcPr()
                shade = OxmlElement('w:shd')
                shade.set(qn('w:fill'), '26384A' if row_index == 0 else ('F1F4F7' if row_index % 2 else 'FFFFFF'))
                tcpr.append(shade)
                for paragraph in cell.paragraphs:
                    paragraph.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
                    paragraph.paragraph_format.line_spacing = 1.05
                    paragraph.paragraph_format.space_after = Pt(3)
                    paragraph.paragraph_format.space_before = Pt(3)
                    paragraph.paragraph_format.keep_with_next = row_index == 0
                    for run in paragraph.runs:
                        run.font.size = Pt(10.5)
                        run.font.bold = row_index == 0
                        run.font.color.rgb = RGBColor(255, 255, 255) if row_index == 0 else RGBColor(0, 0, 0)
        tblpr = table._tbl.tblPr
        borders = OxmlElement('w:tblBorders')
        for side in ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']:
            border = OxmlElement('w:' + side)
            for key, value in [('val', 'single'), ('sz', '4'), ('color', 'D9D9D9')]:
                border.set(qn('w:' + key), value)
            borders.append(border)
        tblpr.append(borders)
        margins = OxmlElement('w:tblCellMar')
        for side in ['top', 'left', 'bottom', 'right']:
            margin = OxmlElement('w:' + side)
            margin.set(qn('w:w'), '90')
            margin.set(qn('w:type'), 'dxa')
            margins.append(margin)
        tblpr.append(margins)
    for p in doc.paragraphs:
        if p.style.style_id == 'SourceCode' or p.style.name == 'Source Code':
            p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
            for run in p.runs:
                run.font.name = 'Consolas'
                run.font.size = Pt(9)
                for fonts in run._r.xpath('./w:rPr/w:rFonts'):
                    for key in list(fonts.attrib):
                        if 'theme' in key.lower():
                            del fonts.attrib[key]
                    for key in ['ascii', 'hAnsi', 'eastAsia', 'cs']:
                        fonts.set(qn('w:' + key), 'Consolas')
        if p._p.xpath('.//w:drawing'):
            p.paragraph_format.keep_with_next = True
            p.paragraph_format.space_before = Pt(6)
            p.paragraph_format.space_after = Pt(0)
        if 'Caption' in p.style.name and not p._p.xpath('.//w:drawing'):
            p.paragraph_format.keep_with_next = False
        plain_heading = re.sub(r'^\d+(?:\.\d+)*\s+', '', p.text)
        if p.style.name == 'Heading 1' and (plain_heading.startswith(('Обнаружение', 'Расследование', 'Регистрация', 'Заключение', 'Приложение'))):
            p.paragraph_format.page_break_before = True
    return doc


def entries_from_markdown(path):
    entries, chapter, sub = [], 0, 0
    for match in re.finditer(r'^(#{1,2}) (.+?) \{#([^ }]+)([^}]*)\}$', path.read_text(encoding='utf-8'), re.M):
        level, title, identifier, classes = len(match[1]), match[2], match[3], match[4]
        number = ''
        if 'unnumbered' not in classes:
            if level == 1:
                chapter, sub = chapter + 1, 0
                number = str(chapter)
            else:
                sub += 1
                number = f'{chapter}.{sub}'
        entries.append({'title': title, 'label': (number + ' ' if number else '') + title,
                        'level': level, 'id': identifier, 'key': re.sub(r'[^\w]', '_', identifier)})
    return entries


def add_bookmark(paragraph, name, identifier):
    start, end = OxmlElement('w:bookmarkStart'), OxmlElement('w:bookmarkEnd')
    start.set(qn('w:id'), str(identifier))
    start.set(qn('w:name'), name)
    end.set(qn('w:id'), str(identifier))
    paragraph.append(start)
    paragraph.append(end)


def add_bookmarks(doc, entries):
    headings = [p for p in doc.paragraphs if p.style.name in ['Heading 1', 'Heading 2']]
    assert len(headings) == len(entries), (len(headings), len(entries))
    from docx.text.paragraph import Paragraph
    paragraphs = list(doc.element.body.iter(qn('w:p')))
    positions = {id(p): i for i, p in enumerate(paragraphs)}
    for index, (p, entry) in enumerate(zip(headings, entries)):
        heading_text = re.sub(r'^\d+(?:\.\d+)*\s+', '', p.text)
        assert heading_text == entry['title'], (p.text, entry['title'])
        # Place the start bookmark at the actual heading, not in the contents.
        start, end = OxmlElement('w:bookmarkStart'), OxmlElement('w:bookmarkEnd')
        start.set(qn('w:id'), str(90000 + index))
        start.set(qn('w:name'), 'start_' + entry['key'])
        end.set(qn('w:id'), str(90000 + index))
        p._p.insert(1 if p._p.pPr is not None else 0, start)
        p._p.append(end)
        begin = positions[id(p._p)]
        stop = next((positions[id(headings[j]._p)] for j in range(index + 1, len(headings))
                     if entries[j]['level'] <= entry['level']), len(paragraphs))
        last = next(el for el in reversed(paragraphs[begin:stop]) if Paragraph(el, doc._body).text.strip())
        add_bookmark(last, 'end_' + entry['key'], 91000 + index)
        entry['end_text'] = Paragraph(last, doc._body).text


def render(path, directory):
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / (path.stem + '.pdf')
    if sys.platform == 'win32':
        script = Path(__file__).with_name('export-word.ps1')
        subprocess.run(['powershell.exe', '-NoProfile', '-File', str(script),
                        '-InputDocx', str(path.resolve()), '-OutputPdf', str(target.resolve()), '-UpdateAndSave'], check=True)
    else:
        executable = shutil.which('libreoffice') or shutil.which('soffice')
        if not executable:
            raise RuntimeError('LibreOffice is required to resolve DOCX page ranges. Install libreoffice-writer.')
        profile = directory / 'lo-profile'
        subprocess.run([executable, '-env:UserInstallation=' + profile.resolve().as_uri(), '--headless',
                        '--convert-to', 'pdf', '--outdir', str(directory), str(path.resolve())], check=True,
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=180)
    assert target.is_file() and target.stat().st_size > 10000
    return target


def page_ranges(pdf_path, entries):
    import pdfplumber
    compact = lambda s: re.sub(r'[\s\u00ad\u200b]', '', s)
    with pdfplumber.open(pdf_path) as pdf:
        texts = [page.extract_text() or '' for page in pdf.pages]
        lines = [[line['text'] for line in page.extract_text_lines(return_chars=False)] for page in pdf.pages]
    answer = []
    for entry in entries:
        key = compact(entry['label'])
        start = []
        for index, values in enumerate(lines):
            if index < 2:
                continue
            candidates = values + [values[j] + values[j + 1] for j in range(len(values) - 1)]
            if key in [compact(value) for value in candidates]:
                start.append(index + 1)
        tail = compact(entry['end_text'])[-60:]
        end = [index + 1 for index, value in enumerate(texts) if index >= 2 and tail in compact(value)]
        assert len(start) == len(end) == 1, (entry['title'], start, end, tail)
        answer.append((start[0], end[0]))
    return answer


def materialize_contents(doc, entries, ranges):
    toc = [p for p in doc.paragraphs if p._p.xpath('.//w:hyperlink[starts-with(@w:anchor,"start_")]')]
    assert len(toc) == len(entries)
    for p, entry, (start, end) in zip(toc, entries, ranges):
        p.clear()
        link = OxmlElement('w:hyperlink')
        link.set(qn('w:anchor'), 'start_' + entry['key'])
        for value in [entry['label'], None, f'{start}–{end}']:
            run = OxmlElement('w:r')
            if value is None:
                run.append(OxmlElement('w:tab'))
            else:
                text = OxmlElement('w:t')
                text.text = value
                run.append(text)
            link.append(run)
        p._p.append(link)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('input', type=Path)
    parser.add_argument('--reference', action='store_true')
    parser.add_argument('--source', type=Path)
    args = parser.parse_args()
    path = args.input.resolve()
    doc = styles(Document(path))
    if args.reference:
        doc.save(path)
        return
    source = args.source.resolve() if args.source else path.with_suffix('.md')
    front = source.read_text(encoding='utf-8').split('---', 2)[1]
    title_match = re.search(r'^title:\s*(.+)$', front, re.M)
    if title_match:
        doc.core_properties.title = title_match[1].strip('\"\'')
    authors = re.findall(r'^\s+-\s+(.+)$', front, re.M)
    doc.core_properties.author = '; '.join(name.strip('\"\'') for name in authors)
    entries = entries_from_markdown(source)
    add_bookmarks(doc, entries)
    doc.save(path)
    qa_dir = source.parent / '.build/docx'
    previous = None
    for attempt in range(3):
        pdf = render(path, qa_dir)
        values = page_ranges(pdf, entries)
        if values == previous:
            break
        doc = Document(path)
        materialize_contents(doc, entries, values)
        doc.save(path)
        previous = values
    else:
        raise RuntimeError('DOCX pagination did not stabilize')
    (qa_dir / 'ranges.json').write_text(json.dumps([dict(entry, start=pair[0], end=pair[1])
        for entry, pair in zip(entries, values)], ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'DOCX complete: {len(entries)} clickable contents entries, page ranges verified')


if __name__ == '__main__':
    main()
